/**
 * Generates docs/validation.md: APD90 and conduction velocity for every preset
 * on the CPU reference solver. Not a pass/fail test beyond sanity ranges; the
 * numbers are the record. Run with: npx vitest run tests/validation
 */
import { expect, test } from 'vitest';
import { writeFileSync } from 'node:fs';
import { PRESETS } from '../../src/model/presets';
import { apd, restitutionCurve, singleCellTrace } from '../../src/model/measures';
import { createSheet, stepSheet, stimulateRect } from '../../src/model/cpuSolver';
import type { FkParams } from '../../src/model/fentonKarma';

function conductionVelocity(p: FkParams, dt: number, dx: number, D: number): number {
  const n = Math.round(6 / dx);
  let cable = createSheet(n, 1, dx);
  cable = stimulateRect(cable, 0, 2, 0, 0, 0.5, 2);
  const probes = [Math.round(2 / dx), Math.round(5 / dx)];
  const arrival: number[] = [];
  let t = 0;
  for (let s = 0; s < 20000 && arrival.length < 2; s++) {
    cable = stepSheet(cable, p, dt, D);
    t += dt;
    if ((cable.u[probes[arrival.length]!] ?? 0) > 0.5) arrival.push(t);
  }
  return arrival.length === 2 ? 3 / (arrival[1]! - arrival[0]!) : NaN;
}

test('validation table', () => {
  const lines = [
    '# Validation table',
    '',
    'Generated by `tests/validation/validation.test.ts` from the CPU reference solver.',
    'APD90 from a single cell stimulated from rest (2 ms, 0.5 current). CV from a 6 cm 1D cable, D = 0.001 cm²/ms.',
    'Restitution: APD90 after an S2 at the given diastolic interval following four 1 s S1 beats.',
    '',
    '| Preset | dt (ms) | APD90 (ms) | CV @0.25 mm (cm/s) | CV @0.4 mm (cm/s) | APD90 @DI 50 / 100 / 200 / 400 ms |',
    '|---|---|---|---|---|---|',
  ];
  for (const preset of PRESETS) {
    const trace = singleCellTrace(preset.params, preset.dt, 1500);
    const apd90 = apd(trace, 0.9);
    expect(apd90, preset.id).not.toBeNull();
    const cvFine = conductionVelocity(preset.params, preset.dt, 0.025, preset.diffusion) * 1000;
    const cvCoarse = conductionVelocity(preset.params, preset.dt, 0.04, preset.diffusion) * 1000;
    expect(cvFine, preset.id).toBeGreaterThan(15);
    expect(cvFine, preset.id).toBeLessThan(90);
    const rest = restitutionCurve(preset.params, preset.dt, [50, 100, 200, 400]).map((r) =>
      r.apd.toFixed(0),
    );
    lines.push(
      `| ${preset.name} | ${preset.dt} | ${apd90!.toFixed(0)} | ${cvFine.toFixed(1)} | ${cvCoarse.toFixed(1)} | ${rest.join(' / ')} |`,
    );
  }
  writeFileSync('docs/validation.md', lines.join('\n') + '\n');
});
